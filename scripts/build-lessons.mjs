// Builds src/data/lessons.ts from docs/content/lessons.json + scripts/lesson-meta.mjs.
// Adds per lesson: index, region key, short title, map pin, stamp label/shape,
// glyphs, instrument parts, route, and resolves Connections to lesson slugs.
// Run: npm run build:lessons

import { readFileSync, writeFileSync } from 'node:fs';
import { LESSON_META, REGIONS, REGION_LABELS, GLYPH_IDS } from './lesson-meta.mjs';

const src = JSON.parse(readFileSync(new URL('../docs/content/lessons.json', import.meta.url), 'utf8'));
const SHAPES = ['circle', 'rect', 'postmark'];
const BANNED = /\b(exotic|primitive|ancient)\b/i;
const glyphSet = new Set(GLYPH_IDS);

const slugByTitle = new Map(src.lessons.map((l) => [l.title, l.slug]));
const problems = [];

const lessons = src.lessons.map((l, index) => {
  const meta = LESSON_META[l.slug];
  if (!meta) throw new Error(`No meta for ${l.slug}`);
  const region = REGIONS[l.region];
  if (!region) throw new Error(`Unknown region ${l.region}`);
  for (const g of [...meta.glyphs, meta.instrument.glyph]) if (!glyphSet.has(g)) problems.push(`${l.slug}: unknown glyph ${g}`);
  const text = JSON.stringify(l);
  if (BANNED.test(text)) problems.push(`${l.slug}: banned word "${text.match(BANNED)[0]}"`);

  const slides = l.slides.map((s) => {
    if (!s.connections) return s;
    return {
      ...s,
      connections: s.connections.map((c) => {
        const slug = slugByTitle.get(c.lesson);
        if (!slug) problems.push(`${l.slug}: connection to unknown lesson "${c.lesson}"`);
        return { lesson: c.lesson, slug, place: c.place, why: c.why };
      }),
    };
  });

  return {
    slug: l.slug,
    index,
    region,
    regionLabel: REGION_LABELS[region],
    title: l.title,
    shortTitle: l.title.split(':')[0].trim(),
    place: l.place,
    era: l.era,
    summary: l.summary,
    pin: meta.pin,
    stamp: meta.stamp,
    stampShape: SHAPES[index % 3],
    country: meta.country,
    glyphs: meta.glyphs,
    instrument: meta.instrument,
    route: meta.route,
    slides,
  };
});

if (problems.length) throw new Error(problems.join('\n'));

const out = `// GENERATED by scripts/build-lessons.mjs from docs/content/lessons.json. Do not edit.
import type { Lesson, RegionKey } from './types';

export const LESSONS: Lesson[] = ${JSON.stringify(lessons, null, 1)};

export const REGION_INTROS: Record<RegionKey, string> = ${JSON.stringify(
  Object.fromEntries(Object.entries(src.regions).map(([label, intro]) => [REGIONS[label], intro])),
  null,
  1,
)};

export const REGION_ORDER: RegionKey[] = ['americas', 'africa', 'asia', 'mena', 'europe'];

export const REGION_LABELS: Record<RegionKey, string> = ${JSON.stringify(REGION_LABELS)};

const bySlug = new Map(LESSONS.map((l) => [l.slug, l]));
export const getLesson = (slug: string) => bySlug.get(slug);
`;

writeFileSync(new URL('../src/data/lessons.ts', import.meta.url), out);
console.log(`lessons.ts: ${lessons.length} lessons, ${(Buffer.byteLength(out) / 1024).toFixed(0)} KB`);
